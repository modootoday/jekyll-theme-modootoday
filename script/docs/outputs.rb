# frozen_string_literal: true

require_relative "../../lib/modootoday/stubs"
require_relative "translations"
require_relative "moves"
require_relative "redirects"
require_relative "releases"

module DocsIndex
  # Everything script/docs-index writes, as { path => content }, built from a Tree.
  # Tool output (twin stubs, llms files) lives under GENERATED, which only this class writes; the redirect stubs of
  # moved demos (Moves) and of pages moved inside the docs (Redirects) sit at the old paths.
  class Outputs
    GENERATED = "generated"
    LLMS = %w[llms llms-full].freeze

    def initialize(tree)
      @t = tree
    end

    def files
      @files ||= fields.merge(moves.files).merge(redirects.files).merge(nav_files).merge(index_lists).merge(releases.files)
        .merge(twins).merge(llms_files)
    end

    def releases = @releases ||= Releases.new(@t, method(:text))

    def translations = @translations ||= Translations.new(@t)
    def moves = @moves ||= Moves.new(@t)
    def redirects = @redirects ||= Redirects.new(@t)

    # Files under GENERATED that no output wants any more.
    def orphans
      llms = Dir.glob("#{@t.root}/#{GENERATED}/**/llms{,-full}.txt").reject { |f| files.key?(f) }
      (stub_twins.orphans.map { |r| "#{@t.root}/#{r}" } + llms).sort
    end

    private

    # lang: and permalink: of each translation, as later outputs read them.
    def fields = @fields ||= translations.files
    def text(path) = fields.fetch(path) { File.read(path) }

    def prefix(lang) = lang == @t.default_lang ? "" : "/#{lang}"

    # One nav file per language whose menu differs from the default one; the others use main.yml
    # (the theme falls back to it), so a language with only a localized home adds no nav file.
    def nav_files
      main = nav(@t.default_lang)
      @t.langs.each_with_object({}) do |lang, h|
        next h["#{@t.root}/_data/nav/main.yml"] = main if lang == @t.default_lang
        body = nav(lang)
        h["#{@t.root}/_data/nav/main-#{lang}.yml"] = body unless body == main
      end
    end

    def nav(lang)
      out = +"# Generated by script/docs-index from docs/_data/sections.yml and page front matter. Do not edit.\n"
      @t.sections.each do |s|
        pages = @t.entries(s["id"], lang)
        idx = @t.index_of(s["id"], lang) || @t.index_of(s["id"], @t.default_lang)
        next if pages.empty? && idx.nil?
        out << "- title: #{q(s.dig("title", lang) || s.dig("title", @t.default_lang))}\n"
        out << "  url: #{idx.url}\n" if idx
        out << "  items:\n" unless pages.empty?
        pages.each { |p| out << item(p, lang) }
      end
      out
    end

    def item(page, lang)
      kids = page.group_index? ? @t.entries(page.dir, lang) : []
      return "    - {title: #{q(page.title)}, url: #{page.url}}\n" if kids.empty?
      "    - title: #{q(page.title)}\n      url: #{page.url}\n      items:\n" +
        kids.map { |k| "        - {title: #{q(k.title)}, url: #{k.url}}\n" }.join
    end

    # Section index pages carry a generated list of their section between spec:docs-index markers.
    def index_lists
      @t.pages.select { |p| p.index? && p.section && p.dir != "." }.each_with_object({}) do |idx, h|
        src = text(idx.path)
        b, e = Modootoday::Markdown::INDEX_MARK % "begin", Modootoday::Markdown::INDEX_MARK % "end"
        next unless src.include?(b) && src.include?(e)
        list = @t.entries(idx.dir, idx.lang).map { |p| "- [#{p.title}](#{rel(idx, p)}) — #{p.fm["description"]}" }
        h[idx.path] = src.sub(/#{Regexp.escape(b)}.*?#{Regexp.escape(e)}/m, "#{b}\n#{list.join("\n")}\n#{e}")
      end
    end

    # Relative link from a section index to a page (Markdown links stay relative, as on GitHub).
    def rel(from, to)
      return to.url.delete_prefix(from.url) if to.url.start_with?(from.url)
      ("../" * (from.url.count("/") - 1)) + to.url.delete_prefix("/")
    end

    # Twin stubs come from the same code as the modootoday-stubs command.
    def twins = stub_twins.wanted.transform_keys { |r| "#{@t.root}/#{r}" }
    def stub_twins = @stub_twins ||= Modootoday::Stubs::Twins.new(source, dir: GENERATED)
    def source
      @source ||= Modootoday::Stubs::Source.new(@t.root).tap do |s|
        s.overlay(fields.transform_keys { |p| p.delete_prefix("#{@t.root}/") }.select { |r, _| r.end_with?(".md") }, [])
      end
    end

    # llms.txt and llms-full.txt for each language with a home page, at /llms.txt and /<lang>/llms.txt.
    # Translations sit beside their sources, so every stub's path: is the root and its lang: picks the pages.
    def llms_files
      homes = @t.pages.select { |p| p.key == "index.md" }.map(&:lang)
      (@t.langs & homes).each_with_object({}) do |lang, h|
        dir = lang == @t.default_lang ? "" : "#{lang}/"
        LLMS.each do |layout|
          fm = lang == @t.default_lang ? "" : "lang: #{lang}\n"
          body = "---\nlayout: #{layout}\n#{fm}path: #{layout}.txt\npermalink: /#{dir}#{layout}.txt\n---\n"
          h["#{@t.root}/#{GENERATED}/#{dir}#{layout}.txt"] = body
        end
      end
    end

    def q(s) = s.to_s.match?(/[:#{}\[\],&*?|<>=!%@`'"]/) ? s.to_s.inspect : s.to_s
  end
end
