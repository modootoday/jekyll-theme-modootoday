# frozen_string_literal: true

module DocsIndex
  MARK = "<!-- spec:docs-index:%s -->"

  # Everything script/docs-index writes, as { path => content }, built from a Tree.
  class Outputs
    def initialize(tree)
      @t = tree
    end

    def files
      @files ||= nav_files.merge(index_lists).merge(twins)
    end

    def orphan_twins
      Dir.glob("#{@t.root}/**/*.md.txt").reject { |f| f.include?("/_site/") || File.exist?(f.delete_suffix(".txt")) }
    end

    private

    def prefix(lang) = lang == @t.default_lang ? "" : "/#{lang}"

    def nav_files
      @t.langs.to_h do |lang|
        name = lang == @t.default_lang ? "main" : "main-#{lang}"
        ["#{@t.root}/_data/nav/#{name}.yml", nav(lang)]
      end
    end

    def nav(lang)
      out = +"# Generated by script/docs-index from docs/_data/sections.yml and page front matter. Do not edit.\n"
      @t.sections.each do |s|
        pages = @t.entries(s["id"], lang)
        idx = @t.index_of(s["id"], lang) || @t.index_of(s["id"], @t.default_lang)
        next if pages.empty? && idx.nil?
        out << "- title: #{q(s.dig("title", lang) || s.dig("title", @t.default_lang))}\n"
        out << "  url: #{idx.url}\n" if idx
        out << "  items:\n" unless pages.empty?
        pages.each { |p| out << item(p, lang) }
      end
      out
    end

    def item(page, lang)
      kids = page.group_index? ? @t.entries(page.dir, lang) : []
      return "    - {title: #{q(page.title)}, url: #{page.url}}\n" if kids.empty?
      "    - title: #{q(page.title)}\n      url: #{page.url}\n      items:\n" +
        kids.map { |k| "        - {title: #{q(k.title)}, url: #{k.url}}\n" }.join
    end

    # Section index pages carry a generated list of their section between spec:docs-index markers.
    def index_lists
      @t.pages.select { |p| p.index? && p.section && p.dir != "." }.each_with_object({}) do |idx, h|
        src = File.read(idx.path)
        b, e = MARK % "begin", MARK % "end"
        next unless src.include?(b) && src.include?(e)
        list = @t.entries(idx.dir, idx.lang).map { |p| "- [#{p.title}](#{rel(idx, p)}) — #{p.fm["description"]}" }
        h[idx.path] = src.sub(/#{Regexp.escape(b)}.*?#{Regexp.escape(e)}/m, "#{b}\n#{list.join("\n")}\n#{e}")
      end
    end

    # Relative link from a section index to a page (Markdown links stay relative, as on GitHub).
    def rel(from, to)
      return to.url.delete_prefix(from.url) if to.url.start_with?(from.url)
      ("../" * (from.url.count("/") - 1)) + to.url.delete_prefix("/")
    end

    def twins
      @t.pages.reject { |p| p.fm.empty? || p.fm["twin"] == false || p.rel.include?("_posts/") }.to_h do |p|
        ["#{p.path}.txt", "---\nlayout: twin\ntwin_of: #{File.basename(p.rel)}\npermalink: #{p.url}index.md\n---\n"]
      end
    end

    def q(s) = s.to_s.match?(/[:#{}\[\],&*?|<>=!%@`'"]/) ? s.to_s.inspect : s.to_s
  end
end
