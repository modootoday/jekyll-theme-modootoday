# frozen_string_literal: true

require "yaml"
require_relative "../../lib/modootoday/markdown"

module DocsIndex
  # The docs Changelog page follows CHANGELOG.md: _data/releases.yml holds every released entry (version, date,
  # tag URL, and per section the count and a short lead of each item), and the reference/changelog pages in every
  # language carry the list made from it between the page-list markers. Release text stays English.
  class Releases
    DATA = "_data/releases.yml"
    PAGE = "reference/changelog"
    LEAD = 90 # characters of an item kept as its lead

    def initialize(tree, read)
      @t = tree
      @read = read
    end

    def files
      h = { "#{@t.root}/#{DATA}" => data }
      @t.pages.select { |p| p.key == "#{PAGE}.md" }.each do |p|
        src = @read.call(p.path)
        b, e = Modootoday::Markdown::INDEX_MARK % "begin", Modootoday::Markdown::INDEX_MARK % "end"
        next unless src.include?(b) && src.include?(e)
        h[p.path] = src.sub(/#{Regexp.escape(b)}.*?#{Regexp.escape(e)}/m, "#{b}\n#{list}\n#{e}")
      end
      h
    end

    def releases
      @releases ||= entries.map do |version, text|
        sections = text.split(/^### /).drop(1).map do |s|
          name, body = s.split("\n", 2)
          items = body.to_s.scan(/^- (.+?)(?=^- |^\S|\z)/m).flatten.map { |i| lead(i) }
          { "name" => name.strip, "count" => items.size, "items" => items }
        end
        { "version" => version, "date" => text[/\A## \[[^\]]+\] - (\S+)/, 1], "url" => links[version], "sections" => sections }
      end
    end

    private

    def changelog = @changelog ||= File.read(File.expand_path("../../CHANGELOG.md", __dir__))
    def links = @links ||= changelog.scan(/^\[([^\]]+)\]: (\S+)$/).to_h

    def entries
      body = changelog[/\A.*?(?=^\[[^\]]+\]: https?:)/m] || changelog
      body.split(/^(?=## \[)/).drop(1).map { |e| [e[/\A## \[([^\]]+)\]/, 1], e] }.reject { |v, _| v == "Unreleased" }
    end

    # The item's opening words: links as their text, cut outside code at the first sentence end, colon or
    # parenthesis, then at a word end within LEAD characters.
    def lead(item)
      t = item.gsub(/\s+/, " ").gsub(/\[([^\]]+)\]\([^)]+\)/, '\1').gsub(/\*\*([^*]+)\*\*/, '\1').strip
      parts = t.split(/(`[^`]*`)/)
      out = +""
      parts.each_with_index do |s, i|
        cut = i.even? && s.index(/(?<=[\w)"])\. |: | \(|;/)
        out << (cut ? s[0, cut] : s)
        break if cut || out.size > LEAD
      end
      out = out.strip.sub(/[.,:]\z/, "")
      return out if out.size <= LEAD
      "#{shorten(out).rstrip.sub(/[,;:]\z/, "")} …"
    end

    def shorten(text)
      out = +""
      text.split(/(`[^`]*`)/).each_with_index do |s, i|
        room = LEAD - out.size
        break if room <= 0
        next out << s if s.size <= room
        out << s[0, room].sub(/\s*\S*\z/, "") if i.even?
        break
      end
      out
    end

    def data
      "# Generated by script/docs-index from CHANGELOG.md. Do not edit.\n#{YAML.dump(releases).delete_prefix("---\n")}"
    end

    def list
      releases.map do |r|
        head = "### [#{r["version"]}](#{r["url"]}) – #{r["date"]}"
        rows = r["sections"].map { |s| "- **#{s["name"]} (#{s["count"]})**\n#{s["items"].map { |i| "  - #{i}" }.join("\n")}" }
        "#{head}\n\n#{rows.join("\n")}"
      end.join("\n\n")
    end
  end
end
