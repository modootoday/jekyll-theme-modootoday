# frozen_string_literal: true

require "yaml"
require_relative "../../lib/modootoday/i18n"
require_relative "../starters/render"

module DocsIndex
  # The docs demos that have moved into published starters, read from the docs demo to starter map
  # (.spec/sot/docs-demo-to-starter-map.sot.md) and example/starters.yml: a redirect stub at each moved shell, feature
  # or record demo, in every language that had it, and _data/starters.yml with the "Live demo" link of each moved demo.
  class Moves
    MAP = ".spec/sot/docs-demo-to-starter-map.sot.md"
    DATA = "_data/starters.yml"
    PREVIEWS = "assets/images/layouts"
    # source: the English page under docs/; page: the path in the starter; en: the docs page has no translations.
    Row = Struct.new(:source, :shows, :starter, :page, :wave, :keep, :en, keyword_init: true) do
      def stub? = keep.start_with?("stub")
      def ref? = keep == "ref"
      def key = source.delete_suffix(".md")
    end

    attr_reader :rows, :done

    # The theme repository holding the map and the starters; tree may be a copy of docs/ elsewhere (tests).
    ROOT = File.expand_path("../..", __dir__)

    def initialize(tree)
      @t = tree
      @root = ROOT
      text = File.read(File.join(@root, MAP))
      @rows = text.lines.grep(/\A\| `/).filter_map { |l| row(l) }
      @done = text.lines.grep(/\A\| \d+ \|.*\| done \|\s*\z/).map { |l| l[/\d+/].to_i }
      theme = Starters::Theme.new(@root)
      @starters = Starters::Manifest.new(File.join(@root, "example/starters.yml"), theme)
    end

    def starter(name) = @starters.fetch(name)
    def moved = rows.select { |r| done.include?(r.wave) }

    # Every moved row with <key> expanded from the starter's pages ("/plugins/<key>/" reads plugins/*.md).
    def expanded
      moved.flat_map do |r|
        next [r] unless r.source.include?("<key>")
        glob = r.page.delete_prefix("/").sub("<key>/", "*.md")
        Dir.glob(glob, base: starter(r.starter).dir).sort.map do |f|
          k = File.basename(f, ".md")
          r.dup.tap { |x| x.source, x.page, x.shows = r.source.sub("<key>", k), r.page.sub("<key>", k), k }
        end
      end
    end

    def url(row, lang = nil)
      s = starter(row.starter)
      dir = lang && lang != s.languages.first && s.languages.include?(lang) ? "#{lang}/" : ""
      "#{s.demo_url}#{dir}#{row.page.delete_prefix("/")}"
    end

    def files = stubs.merge("#{@t.root}/#{DATA}" => data)

    private

    def row(line)
      c = line.split("|")[1..-2].map(&:strip)
      return unless c.size == 6 && c[4].match?(/\A\d+\z/)
      page = c[3][/`([^`]+)`/, 1]
      Row.new(source: c[0][/`([^`]+)`/, 1], shows: c[1], starter: c[2], page: page, wave: c[4].to_i, keep: c[5], en: c[0].include?("(en"))
    end

    def stubs
      expanded.select(&:stub?).each_with_object({}) do |r, h|
        en = stub(r, nil)
        h["#{@t.root}/#{r.source}"] = en
        next if r.en
        full.each do |lang|
          rel = r.source.sub(/\.md\z/, ".#{lang}.md")
          h["#{@t.root}/#{rel}"] = stub(r, lang, en)
        end
      end
    end

    def full = Array(YAML.safe_load(File.read("#{@t.root}/_config.yml")).dig("modootoday", "full_languages"))

    MOVED = { "ko" => "%s 스타터의 데모로 옮겼습니다.", "ja" => "%s スターターのデモに移りました。" }.freeze

    def stub(row, lang, source = nil)
      head = lang ? "lang: #{lang}\npermalink: #{@t.page_lang.url(Modootoday::Stubs::Page.new(row.source, {}).url, lang)}\n" \
                    "source_rev: #{Modootoday::I18n::SourceRev.of(source)}\n" : ""
      moved = format(MOVED.fetch(lang, "Moved to the demo of the %s starter."), row.starter)
      "---\n#{head}title: #{row.shows.capitalize}\ndescription: #{moved}\nlayout: redirect\nredirect_to: #{url(row, lang)}\n" \
        "twin: false\nsitemap: false\nnav_exclude: true\n---\n"
    end

    # The reference pages' links, read by docs/_includes/live-demo.html through docs/_layouts/layout-reference.html.
    def data
      refs = moved.select(&:ref?).sort_by(&:key)
      body = refs.map do |r|
        preview = "/#{PREVIEWS}/#{r.shows}.webp"
        extra = File.file?("#{@t.root}#{preview}") ? ", preview: #{preview}" : ""
        "#{r.key}: {starter: #{r.starter}, url: \"#{url(r)}\"#{extra}}\n"
      end
      "# Generated by script/docs-index from example/starters.yml and #{MAP}. Do not edit.\n#{body.join}"
    end
  end
end
