# frozen_string_literal: true
# Authoring conventions (CONTRIBUTING.md, "Project layout"; .spec ADR "authoring conventions"):
# no flat directories (group files by context) and short, single-purpose code files.
require "minitest/autorun"
require "yaml"
require_relative "../../lib/modootoday/i18n"

class LayoutTest < Minitest::Test
  ROOT = File.expand_path("../..", __dir__)
  MAX_FILES = 12 # tracked files directly in one directory

  # Directories whose shape a standard fixes, or pending a regroup. Each needs a reason.
  FLAT_OK = {
    "." => "gem and repository standard files (README, gemspec, Gemfile, LICENSE, ...)",
    ".spec/adr" => "spec tool convention: one dated record per file",
    "test/fixtures/md" => "fixture corpus: one source file per audit case, named by case",
    "i18n" => "one catalog per language code (23 languages) plus languages.yml and glossary.yml",
    "_includes/modootoday/i18n" => "generated by script/i18n-build: one catalog per language code",
    "docs/_data/i18n" => "Jekyll data: one interface catalog per language code",
    "_layouts" => "theme layout API: file names are the documented layout: values",
    "_includes/modootoday" => "theme include API: paths are documented include names",
  }.freeze

  MAX_LINES = 150 # code files under lib/, exe/, script/, assets/js/ and test/ (system audits, helpers)
  MAX_TEST_LINES = 300 # *_test.rb and *.test.js
  DATA_EXT = %w[.json .txt].freeze # data, not code: lib/modootoday/schema/vocab.txt is one schema.org term per line
  LONG_OK = {}.freeze

  def tracked = @tracked ||= Dir.chdir(ROOT) { `git ls-files -z`.split("\0") }.select { |f| File.file?(File.join(ROOT, f)) }

  # docs/generated/ is written by script/docs-index and is not counted; a docs translation (install.ko.md) counts
  # as its source (install.md), so a directory holds as many files as it has English pages.
  def authored = tracked.reject { |f| f.start_with?("docs/generated/") }.map { |f| f.start_with?("docs/") ? "docs/#{docs_lang.source(f.delete_prefix("docs/"))}" : f }.uniq

  def docs_lang
    @docs_lang ||= begin
      langs = YAML.safe_load(File.read(File.join(ROOT, "docs/_config.yml"))).dig("modootoday", "languages")
      Modootoday::I18n::PageLang.new(langs, langs.first)
    end
  end

  def test_no_flat_directories
    flat = authored.group_by { |f| File.dirname(f) }.select { |d, fs| fs.size > MAX_FILES && !FLAT_OK.key?(d) }
    assert_empty flat.transform_values(&:size), "group these files by context (subdirectories), or add a reason to FLAT_OK"
  end

  def test_flat_allowlist_is_current
    stale = FLAT_OK.keys.reject { |d| authored.count { |f| File.dirname(f) == d } > MAX_FILES }
    assert_empty stale, "no longer flat: remove from FLAT_OK"
  end

  def test_code_files_are_short
    long = code_files.filter_map do |f|
      n = File.foreach(File.join(ROOT, f)).count
      "#{f}: #{n} > #{limit(f)}" if n > limit(f) && !LONG_OK.key?(f)
    end
    assert_empty long, "split by responsibility, or add a reason to LONG_OK"
  end

  def test_long_allowlist_is_current
    stale = LONG_OK.keys.reject { |f| File.file?(File.join(ROOT, f)) && File.foreach(File.join(ROOT, f)).count > limit(f) }
    assert_empty stale, "no longer long: remove from LONG_OK"
  end

  private

  def code_files = tracked.select { |f| f.match?(%r{\A(lib|exe|script|assets/js|test)/}) && !f.start_with?("test/fixtures/") && !f.end_with?(*DATA_EXT) }
  def limit(f) = f.match?(/(_test\.rb|\.test\.js)\z/) ? MAX_TEST_LINES : MAX_LINES
end
